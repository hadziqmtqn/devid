// From the nginx 1.30.6 source tree (BSD-2-Clause, see assets/nginx/LICENSE).
const MIME_TYPES: &str = include_str!("../assets/nginx/mime.types");
const FASTCGI_PARAMS: &str = include_str!("../assets/nginx/fastcgi_params");

fn err(msg: impl Into<String>) -> io::Error {
    io::Error::other(msg.into())
}

pub fn prefix(paths: &Paths) -> PathBuf {
    paths.home.join("nginx")
}

pub fn bin(paths: &Paths) -> PathBuf {
    prefix(paths).join("bin/nginx")
}

pub fn conf(paths: &Paths) -> PathBuf {
    prefix(paths).join("conf/nginx.conf")
}

pub fn pid_file(paths: &Paths) -> PathBuf {
    paths.run_dir().join("nginx.pid")
}

/// Passed with `-e` so nginx never opens its compiled-in error log path before reading the config.
pub fn error_log(paths: &Paths) -> PathBuf {
    paths.log_dir().join("nginx-error.log")
}

pub fn installed(paths: &Paths) -> bool {
    bin(paths).is_file()
}

/// Install an nginx binary (e.g. spike/webservers/out/nginx/nginx).
// shortcut: installs from a local file only; downloading release assets comes with the Phase 5 pipeline.
pub fn install(paths: &Paths, from: &Path) -> io::Result<()> {
    let out = crate::webserver::probe(from, &["-v"])?;
    // nginx prints its version on stderr.
    if !String::from_utf8_lossy(&out.stderr).contains("nginx/") {
        return Err(err(format!("{} does not look like nginx", from.display())));
    }
    let target = bin(paths);
    fs::create_dir_all(target.parent().expect("bin has a parent"))?;
    let tmp = target.with_extension("new");
    fs::copy(from, &tmp)?;
    fs::rename(tmp, target)
}

/// Text that is safe inside a double-quoted nginx string: no quote, backslash, `$` (variable
/// expansion) or control characters. Paths that fail this are left out of the config.
pub(crate) fn quotable(path: &Path) -> Option<String> {
    quotable_without(path, &[])
}

/// Like `quotable`, also rejecting `extra` characters (e.g. `{`/`}`, Caddyfile placeholders).
pub(crate) fn quotable_without(path: &Path, extra: &[char]) -> Option<String> {
    let s = path.to_str()?;
    let bad = |c: char| matches!(c, '"' | '\\' | '$') || c.is_control() || extra.contains(&c);
    (!s.chars().any(bad)).then(|| format!("\"{s}\""))
}

/// The full nginx.conf for these sites. Sites whose paths cannot be quoted safely are skipped
/// with a comment, so one odd folder name cannot break every other site.
pub fn render(paths: &Paths, config: &Config, sites: &[Site]) -> String {
    let (port, https) = (config.http_port, config.https_port);
    let q = |p: &Path| quotable(p).expect("Devid's own paths are quotable");
    let mut c = format!(
        "# Generated by Devid; changes are overwritten.\n\
         worker_processes 1;\n\
         pid {pid};\n\
         error_log {log} warn;\n\
         events {{ worker_connections 256; }}\n\
         \n\
         http {{\n\
         \x20   include mime.types;\n\
         \x20   default_type application/octet-stream;\n\
         \x20   access_log off;\n\
         \x20   sendfile on;\n\
         \x20   gzip on;\n\
         \x20   client_max_body_size 64m;\n\
         \x20   client_body_temp_path {body};\n\
         \x20   fastcgi_temp_path {fastcgi};\n\
         \x20   proxy_temp_path {proxy};\n\
         \n\
         \x20   server {{\n\
         \x20       listen 127.0.0.1:{port} default_server;\n\
         \x20       default_type text/plain;\n\
         \x20       return 404 \"No Devid site for this host.\\n\";\n\
         \x20   }}\n\
         \x20   # Unknown hosts on HTTPS: refuse the handshake instead of serving a wrong certificate.\n\
         \x20   server {{\n\
         \x20       listen 127.0.0.1:{https} ssl default_server;\n\
         \x20       ssl_reject_handshake on;\n\
         \x20   }}\n",
        pid = q(&pid_file(paths)),
        log = q(&error_log(paths)),
        body = q(&prefix(paths).join("tmp/body")),
        fastcgi = q(&prefix(paths).join("tmp/fastcgi")),
        proxy = q(&prefix(paths).join("tmp/proxy")),
    );
    // WebSocket upgrades (dev servers' HMR) pass through proxy sites.
    c.push_str("    map $http_upgrade $connection_upgrade { default upgrade; '' close; }\n");
    for site in sites {
        let (Some(crt), Some(key)) =
            (quotable(&ca::site_cert(paths, &site.host)), quotable(&ca::site_key(paths, &site.host)))
        else {
            let _ = writeln!(c, "\n    # skipped {}: path contains characters nginx cannot quote safely", site.name);
            continue;
        };
        let Some(body) = site_body(paths, site) else {
            let _ = writeln!(c, "\n    # skipped {}: path contains characters nginx cannot quote safely", site.name);
            continue;
        };
        if site.mode == Mode::Proxy && !site.pass_host {
            let _ = write!(c, "{}", own_origin_map(config, site));
        }
        let _ = write!(
            c,
            "\n    server {{\n\
             \x20       listen 127.0.0.1:{port};\n\
             \x20       listen 127.0.0.1:{https} ssl;\n\
             \x20       http2 on;\n\
             \x20       ssl_certificate {crt};\n\
             \x20       ssl_certificate_key {key};\n\
             \x20       server_name {host};\n\
             {body}\
             \x20   }}\n",
            host = site.host,
        );
    }
    c.push_str("}\n");
    c
}

/// nginx variable holding the Origin a proxy site sends upstream (site names are DNS labels).
fn origin_var(site: &Site) -> String {
    format!("$devid_origin_{}", site.name.replace('-', "_"))
}

/// The site's own origins (any port) become the dev server's, so Next.js and Vite accept their
/// own pages (A1); any other Origin passes unchanged and is still refused by the dev server.
fn own_origin_map(config: &Config, site: &Site) -> String {
    let (host, up) = (&site.host, site.upstream);
    let mut m = format!("\n    map $http_origin {} {{\n        default $http_origin;\n", origin_var(site));
    for origin in [
        format!("https://{host}"),
        format!("https://{host}:{}", config.https_port),
        format!("http://{host}"),
        format!("http://{host}:{}", config.http_port),
    ] {
        let _ = writeln!(m, "        \"{origin}\" \"http://localhost:{up}\";");
    }
    m.push_str("    }\n");
    m
}

/// The part of a site's server block that depends on its mode; None if a path cannot be quoted.
fn site_body(paths: &Paths, site: &Site) -> Option<String> {
    let hidden = "        location ~ /\\.(?!well-known).* { deny all; }\n";
    Some(match site.mode {
        Mode::Php => {
            let root = quotable(&site.docroot)?;
            let sock = quotable(Path::new(&format!("unix:{}", php::socket(paths, &site.php).display())))?;
            format!(
                "        root {root};\n\
                 \x20       index index.php index.html;\n\
                 \x20       charset utf-8;\n\
                 \x20       location / {{ try_files $uri $uri/ /index.php?$query_string; }}\n\
                 \x20       location ~ \\.php$ {{\n\
                 \x20           fastcgi_pass {sock};\n\
                 \x20           fastcgi_param SCRIPT_FILENAME $realpath_root$fastcgi_script_name;\n\
                 \x20           include fastcgi_params;\n\
                 \x20           # Laravel/Inertia headers exceed nginx's 4k default (spike, D-015).\n\
                 \x20           fastcgi_buffer_size 32k;\n\
                 \x20           fastcgi_buffers 16 16k;\n\
                 \x20       }}\n\
                 {hidden}"
            )
        }
        Mode::Static => {
            let root = quotable(&site.docroot)?;
            // `$uri.html` serves static exports such as Next.js `out/about.html` at /about.
            let last = if site.spa { "/index.html" } else { "=404" };
            format!(
                "        root {root};\n\
                 \x20       index index.html;\n\
                 \x20       charset utf-8;\n\
                 \x20       location / {{ try_files $uri $uri.html $uri/ {last}; }}\n\
                 {hidden}"
            )
        }
        Mode::Proxy => {
            let up = site.upstream;
            let (host, origin) = match site.pass_host {
                true => ("$host".to_string(), "$http_origin".to_string()),
                false => (format!("localhost:{up}"), origin_var(site)),
            };
            // `localhost` resolves to 127.0.0.1 and ::1, and nginx tries both: Vite listens on
            // [::1] only by default (A1).
            format!(
                "        location / {{\n\
                 \x20           proxy_pass http://localhost:{up};\n\
                 \x20           proxy_http_version 1.1;\n\
                 \x20           proxy_set_header Host {host};\n\
                 \x20           proxy_set_header Origin {origin};\n\
                 \x20           proxy_set_header Upgrade $http_upgrade;\n\
                 \x20           proxy_set_header Connection $connection_upgrade;\n\
                 \x20           proxy_set_header X-Forwarded-Host $host;\n\
                 \x20           proxy_set_header X-Forwarded-Proto $scheme;\n\
                 \x20           proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n\
                 \x20           # Dev servers stream (SSE, HMR); keep idle WebSockets open.\n\
                 \x20           proxy_buffering off;\n\
                 \x20           proxy_read_timeout 1h;\n\
                 \x20       }}\n\
                 \x20       error_page 502 504 = @devid_down;\n\
                 \x20       location @devid_down {{\n\
                 \x20           default_type text/plain;\n\
                 \x20           return 502 \"Nothing answers on localhost:{up} for {name}. Start its dev server (or its command in Devid).\\n\";\n\
                 \x20       }}\n",
                name = site.host,
            )
        }
    })
}

/// Write the config only if `nginx -t` accepts it; on failure the previous config stays active.
/// Returns whether the config changed.
pub fn write_checked(paths: &Paths, text: &str) -> io::Result<bool> {
    let conf = conf(paths);
    if fs::read_to_string(&conf).is_ok_and(|old| old == text) {
        return Ok(false);
    }
    let dir = conf.parent().expect("conf has a parent");
    fs::create_dir_all(dir)?;
    fs::create_dir_all(prefix(paths).join("tmp"))?;
    fs::create_dir_all(paths.log_dir())?;
    fs::write(dir.join("mime.types"), MIME_TYPES)?;
    fs::write(dir.join("fastcgi_params"), FASTCGI_PARAMS)?;

    let candidate = dir.join("nginx.conf.new");
    fs::write(&candidate, text)?;
    let out = Command::new(bin(paths))
        .arg("-t")
        .arg("-e")
        .arg(error_log(paths))
        .arg("-p")
        .arg(prefix(paths))
        .arg("-c")
        .arg(&candidate)
        .output()?;
    if !out.status.success() {
        let _ = fs::remove_file(&candidate);
        return Err(err(format!("nginx rejected the new config: {}", String::from_utf8_lossy(&out.stderr).trim())));
    }
    fs::rename(candidate, conf)?;
    Ok(true)
}

pub fn spec(paths: &Paths) -> Spec {
    Spec {
        program: bin(paths),
        args: vec![
            "-e".into(),
            error_log(paths).into(),
            "-p".into(),
            prefix(paths).into(),
            "-c".into(),
            conf(paths).into(),
            "-g".into(),
            "daemon off;".into(),
        ],
        env: Vec::new(),
        pid_file: pid_file(paths),
        comm: "nginx",
        stop_signal: libc::SIGQUIT,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn site(name: &str, docroot: &str, php: &str) -> Site {
        Site {
            name: name.into(),
            host: format!("{name}.test"),
            path: PathBuf::from(docroot),
            docroot: PathBuf::from(docroot),
            php: php.into(),
            linked: true,
            preset: "php",
            ..Site::default()
        }
    }

    #[test]
    fn render_sites() {
        let paths = Paths { home: PathBuf::from("/h/.devid") };
        let config = Config::default();
        let conf = render(
            &paths,
            &config,
            &[site("blog", "/p/blog/public", "8.4"), site("evil", "/p/$evil\"; } server { x", "8.5")],
        );
        assert!(conf.contains("listen 127.0.0.1:8088 default_server;"));
        assert!(conf.contains("listen 127.0.0.1:8443 ssl default_server;"));
        assert!(conf.contains("ssl_certificate \"/h/.devid/certs/blog.test.crt\";"));
        assert!(conf.contains("listen 127.0.0.1:8443 ssl;"));
        assert!(conf.contains("server_name blog.test;"));
        assert!(conf.contains("root \"/p/blog/public\";"));
        assert!(conf.contains("fastcgi_pass \"unix:/h/.devid/run/php84.sock\";"));
        assert!(conf.contains("client_body_temp_path \"/h/.devid/nginx/tmp/body\";"));
        assert!(conf.contains("fastcgi_buffer_size 32k;"));
        assert!(conf.contains("# skipped evil"), "unsafe path is skipped, not injected");
        assert!(!conf.contains("$evil"));
        assert_eq!(conf.matches("server {").count(), 3, "HTTP and HTTPS default servers + blog");
        assert!(!conf.contains("proxy_pass"), "PHP sites are served as before");
    }

    #[test]
    fn render_static_and_proxy() {
        let paths = Paths { home: PathBuf::from("/h/.devid") };
        let spa = Site { mode: Mode::Static, spa: true, ..site("app", "/p/app/dist", "8.4") };
        let plain = Site { mode: Mode::Static, ..site("lp", "/p/lp", "8.4") };
        let dev = Site { mode: Mode::Proxy, upstream: 5173, ..site("erd-pro", "/p/erd", "8.4") };
        let raw = Site { mode: Mode::Proxy, upstream: 3000, pass_host: true, ..site("raw", "/p/raw", "8.4") };
        let conf = render(&paths, &Config::default(), &[spa, plain, dev, raw]);

        assert!(conf.contains("root \"/p/app/dist\";") && conf.contains("try_files $uri $uri.html $uri/ /index.html;"));
        assert!(conf.contains("try_files $uri $uri.html $uri/ =404;"), "no SPA fallback unless asked");
        assert!(!conf.contains("fastcgi_pass"), "static and proxy sites need no php-fpm");

        assert!(conf.contains("proxy_pass http://localhost:5173;"));
        assert!(conf.contains("proxy_set_header Host localhost:5173;"));
        assert!(conf.contains("map $http_origin $devid_origin_erd_pro {"));
        for own in
            ["https://erd-pro.test", "https://erd-pro.test:8443", "http://erd-pro.test", "http://erd-pro.test:8088"]
        {
            assert!(conf.contains(&format!("\"{own}\" \"http://localhost:5173\";")), "{own}");
        }
        assert!(conf.contains("proxy_set_header Origin $devid_origin_erd_pro;"));
        assert!(conf.contains("proxy_set_header Connection $connection_upgrade;"));
        assert!(conf.contains("return 502 \"Nothing answers on localhost:5173 for erd-pro.test."));

        assert!(
            conf.contains("proxy_set_header Host $host;") && conf.contains("proxy_set_header Origin $http_origin;")
        );
        assert!(!conf.contains("$devid_origin_raw"), "pass_host keeps Host and Origin");
        assert_eq!(conf.matches("map $http_upgrade").count(), 1);
    }
}
