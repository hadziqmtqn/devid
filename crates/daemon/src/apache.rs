//! Apache, an alternative web server (D-005, D-015): the macOS system httpd (Apple-signed, with
//! mod_proxy_fcgi, mod_ssl and mod_http2; see the spike), run as the owner with a Devid-owned
//! config. `/etc/apache2` is never read or touched.

use crate::{ca, config::Config, nginx::quotable, paths::Paths, php, sites::Site, supervisor::Spec};
use std::{
    fmt::Write as _,
    fs, io,
    os::unix::fs::symlink,
    path::{Path, PathBuf},
    process::Command,
};

pub const SYSTEM_HTTPD: &str = "/usr/sbin/httpd";
/// Modules from `ServerRoot` (/usr on macOS). Unix-only paths; Apache is a macOS adapter (D-013).
const MODULES: [(&str, &str); 16] = [
    ("mpm_event_module", "mod_mpm_event.so"),
    ("authz_core_module", "mod_authz_core.so"),
    ("unixd_module", "mod_unixd.so"),
    ("mime_module", "mod_mime.so"),
    ("dir_module", "mod_dir.so"),
    ("rewrite_module", "mod_rewrite.so"),
    ("setenvif_module", "mod_setenvif.so"),
    ("headers_module", "mod_headers.so"),
    ("deflate_module", "mod_deflate.so"),
    ("filter_module", "mod_filter.so"),
    ("proxy_module", "mod_proxy.so"),
    ("proxy_fcgi_module", "mod_proxy_fcgi.so"),
    ("socache_shmcb_module", "mod_socache_shmcb.so"),
    ("ssl_module", "mod_ssl.so"),
    ("http2_module", "mod_http2.so"),
    ("log_config_module", "mod_log_config.so"),
];

fn err(msg: impl Into<String>) -> io::Error {
    io::Error::other(msg.into())
}

pub fn dir(paths: &Paths) -> PathBuf {
    paths.home.join("apache")
}

/// A symlink to the system httpd, so "installed" means the same for every server.
pub fn bin(paths: &Paths) -> PathBuf {
    dir(paths).join("bin/httpd")
}

pub fn conf(paths: &Paths) -> PathBuf {
    dir(paths).join("httpd.conf")
}

pub fn pid_file(paths: &Paths) -> PathBuf {
    paths.run_dir().join("httpd.pid")
}

pub fn installed(paths: &Paths) -> bool {
    bin(paths).is_file()
}

/// Point Devid at an httpd binary, by default the macOS system one.
pub fn install(paths: &Paths, from: Option<&Path>) -> io::Result<()> {
    let from = from.unwrap_or(Path::new(SYSTEM_HTTPD));
    let out = crate::webserver::probe(from, &["-v"])?;
    if !String::from_utf8_lossy(&out.stdout).contains("Apache/2.4") {
        return Err(err(format!("{} does not look like Apache 2.4", from.display())));
    }
    let target = bin(paths);
    fs::create_dir_all(target.parent().expect("bin has a parent"))?;
    let _ = fs::remove_file(&target);
    symlink(from, target)
}

/// One httpd.conf for all sites, on 127.0.0.1 only. Unsafe paths are skipped with a comment.
pub fn render(paths: &Paths, config: &Config, sites: &[Site]) -> String {
    let (http, https) = (config.http_port, config.https_port);
    let q = |p: &Path| quotable(p).expect("Devid's own paths are quotable");
    let run = q(&paths.run_dir());
    let mut c = format!(
        "# Generated by Devid; changes are overwritten.\n\
         ServerRoot \"/usr\"\n\
         ServerName localhost\n\
         Listen 127.0.0.1:{http}\n\
         Listen 127.0.0.1:{https} https\n\
         PidFile {pid}\n\
         DefaultRuntimeDir {run}\n\
         Mutex file:{run_unquoted} default\n\
         ErrorLog {log}\n\
         LogLevel warn\n",
        pid = q(&pid_file(paths)),
        run_unquoted = paths.run_dir().display(),
        log = q(&paths.log_dir().join("apache-error.log")),
    );
    for (name, file) in MODULES {
        let _ = writeln!(c, "LoadModule {name} libexec/apache2/{file}");
    }
    let _ = write!(
        c,
        "TypesConfig /private/etc/apache2/mime.types\n\
         StartServers 1\n\
         ServerLimit 1\n\
         ThreadsPerChild 25\n\
         MaxRequestWorkers 25\n\
         Protocols h2 http/1.1\n\
         SSLSessionCache none\n\
         DirectoryIndex index.php index.html\n\
         <Directory />\n\
         \x20   AllowOverride None\n\
         \x20   Require all denied\n\
         </Directory>\n\
         <FilesMatch \"^\\.(?!well-known)\">\n\
         \x20   Require all denied\n\
         </FilesMatch>\n\
         \n\
         # First vhost per port is the fallback for unknown hosts.\n\
         <VirtualHost 127.0.0.1:{http}>\n\
         \x20   ServerName unknown.invalid\n\
         \x20   RewriteEngine on\n\
         \x20   RewriteRule ^ - [R=404,L]\n\
         </VirtualHost>\n"
    );
    // shortcut: the first HTTPS vhost also answers unknown hosts (Apache needs a certificate for its
    // default vhost); nginx refuses those handshakes instead. Upgrade if it ever matters.
    for site in sites {
        let sock = php::socket(paths, &site.php);
        let (Some(root), Some(crt), Some(key)) = (
            quotable(&site.docroot),
            quotable(&ca::site_cert(paths, &site.host)),
            quotable(&ca::site_key(paths, &site.host)),
        ) else {
            let _ = writeln!(c, "\n# skipped {}: path contains characters Apache cannot quote safely", site.name);
            continue;
        };
        if quotable(&sock).is_none() {
            let _ = writeln!(c, "\n# skipped {}: socket path cannot be quoted safely", site.name);
            continue;
        }
        let common = format!(
            "\x20   ServerName {host}\n\
             \x20   DocumentRoot {root}\n\
             \x20   <Directory {root}>\n\
             \x20       AllowOverride All\n\
             \x20       Require all granted\n\
             \x20   </Directory>\n\
             \x20   <FilesMatch \"\\.php$\">\n\
             \x20       SetHandler \"proxy:unix:{sock}|fcgi://localhost\"\n\
             \x20   </FilesMatch>\n",
            host = site.host,
            sock = sock.display(),
        );
        let _ = write!(
            c,
            "\n<VirtualHost 127.0.0.1:{http}>\n{common}</VirtualHost>\n\
             <VirtualHost 127.0.0.1:{https}>\n{common}\
             \x20   SSLEngine on\n\
             \x20   SSLCertificateFile {crt}\n\
             \x20   SSLCertificateKeyFile {key}\n\
             </VirtualHost>\n"
        );
    }
    c
}

/// Write httpd.conf only if `httpd -t` accepts it. Returns whether it changed.
pub fn write_checked(paths: &Paths, text: &str) -> io::Result<bool> {
    let conf = conf(paths);
    if fs::read_to_string(&conf).is_ok_and(|old| old == text) {
        return Ok(false);
    }
    fs::create_dir_all(dir(paths))?;
    fs::create_dir_all(paths.log_dir())?;
    let candidate = conf.with_extension("new");
    fs::write(&candidate, text)?;
    let out = Command::new(bin(paths)).arg("-t").arg("-f").arg(&candidate).output()?;
    if !out.status.success() {
        let _ = fs::remove_file(&candidate);
        return Err(err(format!("apache rejected the new config: {}", String::from_utf8_lossy(&out.stderr).trim())));
    }
    fs::rename(candidate, conf)?;
    Ok(true)
}

pub fn spec(paths: &Paths) -> Spec {
    Spec {
        program: bin(paths),
        args: vec!["-f".into(), conf(paths).into(), "-DFOREGROUND".into()],
        env: Vec::new(),
        pid_file: pid_file(paths),
        comm: "httpd",
        // SIGTERM stops Apache and its children; it does not handle SIGQUIT.
        stop_signal: libc::SIGTERM,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_sites() {
        let paths = Paths { home: PathBuf::from("/h/.devid") };
        let blog = Site {
            name: "blog".into(),
            host: "blog.test".into(),
            path: "/p/blog".into(),
            docroot: "/p/blog/public".into(),
            php: "8.4".into(),
            isolated: true,
            linked: false,
        };
        let evil = Site { name: "evil".into(), host: "evil.test".into(), docroot: "/p/\"x".into(), ..blog.clone() };
        let conf = render(&paths, &Config::default(), &[blog, evil]);
        assert!(conf.contains("Listen 127.0.0.1:8088\n") && conf.contains("Listen 127.0.0.1:8443 https\n"));
        assert!(conf.contains("ServerName blog.test"));
        assert!(conf.contains("SetHandler \"proxy:unix:/h/.devid/run/php84.sock|fcgi://localhost\""));
        assert!(conf.contains("SSLCertificateFile \"/h/.devid/certs/blog.test.crt\""));
        assert!(conf.contains("LoadModule proxy_fcgi_module"));
        assert!(conf.contains("# skipped evil"));
        assert!(!conf.contains("/etc/apache2/httpd.conf"), "never the system config");
    }
}
