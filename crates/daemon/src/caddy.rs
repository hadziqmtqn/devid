//! Caddy, an alternative web server (D-005, D-015). Devid owns the certificates, so automatic
//! HTTPS and the admin API are off; a config change restarts Caddy (it has no SIGHUP reload).

use crate::{
    ca,
    config::Config,
    nginx::quotable_without,
    paths::Paths,
    php,
    sites::{Mode, Site},
    supervisor::Spec,
    webserver::NO_SITE,
};
use std::{
    fmt::Write as _,
    fs, io,
    path::{Path, PathBuf},
    process::Command,
};

fn err(msg: impl Into<String>) -> io::Error {
    io::Error::other(msg.into())
}

/// Caddyfile placeholders use braces, so paths with `{`/`}` are rejected as well.
fn quote(path: &Path) -> Option<String> {
    quotable_without(path, &['{', '}'])
}

pub fn dir(paths: &Paths) -> PathBuf {
    paths.home.join("caddy")
}

pub fn bin(paths: &Paths) -> PathBuf {
    dir(paths).join("bin/caddy")
}

pub fn conf(paths: &Paths) -> PathBuf {
    dir(paths).join("Caddyfile")
}

pub fn installed(paths: &Paths) -> bool {
    bin(paths).is_file()
}

/// Install a Caddy v2 binary (e.g. the official release).
// shortcut: installs from a local file only; downloading release assets comes with the Phase 5 pipeline.
pub fn install(paths: &Paths, from: &Path) -> io::Result<()> {
    let out = crate::webserver::probe(from, &["version"])?;
    if !String::from_utf8_lossy(&out.stdout).trim_start().starts_with("v2.") {
        return Err(err(format!("{} does not look like Caddy v2", from.display())));
    }
    let target = bin(paths);
    fs::create_dir_all(target.parent().expect("bin has a parent"))?;
    let tmp = target.with_extension("new");
    fs::copy(from, &tmp)?;
    fs::rename(tmp, target)
}

/// One Caddyfile for all sites, on 127.0.0.1 only. Unsafe paths are skipped with a comment.
pub fn render(paths: &Paths, config: &Config, sites: &[Site]) -> String {
    let (http, https) = (config.http_port, config.https_port);
    let q = |p: &Path| quote(p).expect("Devid's own paths are quotable");
    let mut c = format!(
        "# Generated by Devid; changes are overwritten.\n\
         {{\n\
         \tadmin off\n\
         \tauto_https off\n\
         \t# A tunnel on a local port (D-037) runs on this Mac; keep its X-Forwarded-* headers.\n\
         \tservers {{\n\
         \t\ttrusted_proxies static 127.0.0.1/8 ::1\n\
         \t}}\n\
         \tstorage file_system {data}\n\
         \tlog {{\n\
         \t\toutput file {log}\n\
         \t\tlevel WARN\n\
         \t}}\n\
         }}\n\
         \n\
         http://:{http} {{\n\
         \tbind 127.0.0.1\n\
         \trespond \"{NO_SITE}\" 404\n\
         }}\n",
        data = q(&dir(paths).join("data")),
        log = q(&paths.log_dir().join("caddy-error.log")),
    );
    for site in sites {
        let (Some(crt), Some(key), Some(body)) =
            (quote(&ca::site_cert(paths, &site.host)), quote(&ca::site_key(paths, &site.host)), site_body(paths, site))
        else {
            let _ = writeln!(c, "\n# skipped {}: path contains characters Caddy cannot quote safely", site.name);
            continue;
        };
        // Caddy rejects `tls` in a block that also listens on plain HTTP, so each site gets an
        // HTTPS block and an HTTP block with the same body.
        let _ = write!(
            c,
            "\nhttps://{host}:{https} {{\n\
             \tbind 127.0.0.1\n\
             \ttls {crt} {key}\n\
             {body}\
             }}\n\
             \nhttp://{host}:{http} {{\n\
             \tbind 127.0.0.1\n\
             {body}\
             }}\n",
            host = site.host,
        );
        // D-037: plain HTTP on 127.0.0.1:<port>, any Host (a tunnel sends its public name).
        if let Some(local) = site.port {
            let _ = write!(c, "\n# {} on its local port\nhttp://:{local} {{\n\tbind 127.0.0.1\n{body}}}\n", site.name);
        }
    }
    c
}

/// The part of a site's blocks that depends on its mode; None if a path cannot be quoted.
fn site_body(paths: &Paths, site: &Site) -> Option<String> {
    let hidden = "\t@hidden {\n\t\tpath /.*\n\t\tnot path /.well-known/*\n\t}\n\trespond @hidden 403\n";
    Some(match site.mode {
        Mode::Php => {
            let root = quote(&site.docroot)?;
            let sock = quote(Path::new(&format!("unix/{}", php::socket(paths, &site.php).display())))?;
            format!("\troot * {root}\n\tencode\n{hidden}\tphp_fastcgi {sock}\n\tfile_server\n")
        }
        Mode::Static => {
            let root = quote(&site.docroot)?;
            let spa = if site.spa { " /index.html" } else { "" };
            format!("\troot * {root}\n\tencode\n{hidden}\ttry_files {{path}} {{path}}.html{spa}\n\tfile_server\n")
        }
        Mode::Proxy => {
            let (host, up) = (&site.host, site.upstream);
            let message = format!(
                "Nothing answers on localhost:{up} for {host}. Start its dev server (or its command in Devid)."
            );
            // As in nginx: Host and the site's own Origin become the dev server's (A1).
            let origin = match site.pass_host {
                true => String::new(),
                false => format!(
                    "\t@devid_own_origin header_regexp Origin \"^https?://{own}(:[0-9]+)?$\"\n\
                     \trequest_header @devid_own_origin Origin http://localhost:{up}\n",
                    own = host.replace('.', "[.]"),
                ),
            };
            let down = match &site.on_demand {
                None => format!("\thandle_errors 502 {{\n\t\trespond \"{message}\" 502\n\t}}\n"),
                Some(_) => on_demand(paths, site, &message)?,
            };
            format!("{origin}{}{down}", proxy(site, 1))
        }
    })
}

/// The proxy to a site's dev server, indented by `tabs`.
fn proxy(site: &Site, tabs: usize) -> String {
    let (t, up) = ("\t".repeat(tabs), site.upstream);
    let mut options = String::new();
    if !site.pass_host {
        options.push_str(&format!("{t}\theader_up Host localhost:{up}\n"));
    }
    // On demand: no idle connections kept open to the dev server, which the idle check would take
    // for an open tab (a dev server that never closes them kept the site awake), as with nginx.
    if site.on_demand.is_some() {
        options.push_str(&format!("{t}\ttransport http {{\n{t}\t\tkeepalive off\n{t}\t}}\n"));
    }
    match options.is_empty() {
        true => format!("{t}reverse_proxy localhost:{up}\n"),
        false => format!("{t}reverse_proxy localhost:{up} {{\n{options}{t}}}\n"),
    }
}

/// D-054: an on-demand site's request file and wake-up (see `ondemand`); None if a path cannot be
/// quoted.
/// - **Request file:** short access-log lines in `run/requests-<site>`; the idle check reads its
///   modification time.
/// - **Wake-up:** a dial error means the dev server is down and never got the request (a server
///   that took it and closed gives `EOF` or a write error instead). That request goes to the wake
///   socket as a GET without its body, its method in `X-Devid-Method`. On the daemon's 418 the
///   same request, body included, goes to the dev server; any other answer goes to the client.
/// - **Limits:** an error inside `handle_errors` cannot be handled again, so if the wake socket
///   does not answer (the daemon is down) or the dev server refuses again after the 418, the
///   client gets an empty 502.
fn on_demand(paths: &Paths, site: &Site, message: &str) -> Option<String> {
    let requests = quote(&paths.last_request(&site.name))?;
    let wake = quote(Path::new(&format!("unix/{}", paths.wake_socket().display())))?;
    Some(format!(
        "\tlog {{\n\
         \t\toutput file {requests} {{\n\
         \t\t\troll_disabled\n\
         \t\t}}\n\
         \t\tformat filter {{\n\
         \t\t\trequest delete\n\
         \t\t\tresp_headers delete\n\
         \t\t}}\n\
         \t}}\n\
         \thandle_errors 502 {{\n\
         \t\t@devid_refused vars_regexp {{http.error.message}} \"^dial \"\n\
         \t\thandle @devid_refused {{\n\
         \t\t\treverse_proxy {wake} {{\n\
         \t\t\t\tmethod GET\n\
         \t\t\t\theader_up X-Devid-Site {name}\n\
         \t\t\t\theader_up X-Devid-Method {{method}}\n\
         \t\t\t\t@devid_ready status 418\n\
         \t\t\t\thandle_response @devid_ready {{\n\
         {retry}\
         \t\t\t\t}}\n\
         \t\t\t}}\n\
         \t\t}}\n\
         \t\thandle {{\n\
         \t\t\trespond \"{message}\" 502\n\
         \t\t}}\n\
         \t}}\n",
        name = site.name,
        retry = proxy(site, 5),
    ))
}

/// Write the Caddyfile only if `caddy validate` accepts it. Returns whether it changed.
pub fn write_checked(paths: &Paths, text: &str) -> io::Result<bool> {
    let conf = conf(paths);
    if fs::read_to_string(&conf).is_ok_and(|old| old == text) {
        return Ok(false);
    }
    fs::create_dir_all(dir(paths).join("data"))?;
    fs::create_dir_all(paths.log_dir())?;
    let candidate = conf.with_extension("new");
    fs::write(&candidate, text)?;
    let out =
        Command::new(bin(paths)).args(["validate", "--adapter", "caddyfile", "--config"]).arg(&candidate).output()?;
    if !out.status.success() {
        let _ = fs::remove_file(&candidate);
        let detail = String::from_utf8_lossy(&out.stderr);
        let last = detail.lines().rev().find(|l| !l.trim().is_empty()).unwrap_or("").trim();
        return Err(err(format!("caddy rejected the new config: {last}")));
    }
    fs::rename(candidate, conf)?;
    Ok(true)
}

pub fn spec(paths: &Paths) -> Spec {
    Spec {
        program: bin(paths),
        args: vec!["run".into(), "--adapter".into(), "caddyfile".into(), "--config".into(), conf(paths).into()],
        // Caddy reads XDG dirs for autosave; keep them inside Devid's folder.
        env: vec![
            ("XDG_DATA_HOME".into(), dir(paths).join("data").into()),
            ("XDG_CONFIG_HOME".into(), dir(paths).join("config").into()),
        ],
        // Caddy writes no pid file; the supervisor tracks the child directly.
        pid_file: paths.run_dir().join("caddy.pid"),
        write_pid: false,
        comm: "caddy",
        stop_signal: libc::SIGTERM,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn site(name: &str, docroot: &str, php: &str) -> Site {
        Site {
            name: name.into(),
            host: format!("{name}.test"),
            path: PathBuf::from(docroot),
            docroot: PathBuf::from(docroot),
            php: php.into(),
            linked: true,
            preset: "php",
            ..Site::default()
        }
    }

    #[test]
    fn render_sites() {
        let paths = Paths { home: PathBuf::from("/h/.devid") };
        let conf = render(
            &paths,
            &Config::default(),
            &[site("blog", "/p/blog/public", "8.4"), site("evil", "/p/{env.HOME}", "8.5")],
        );
        assert!(conf.contains("admin off") && conf.contains("auto_https off"));
        assert!(conf.contains("https://blog.test:8443 {") && conf.contains("http://blog.test:8088 {"));
        assert!(!conf.contains(", https://"), "Caddy rejects http and https addresses sharing a tls block");
        assert!(conf.contains("tls \"/h/.devid/certs/blog.test.crt\" \"/h/.devid/certs/blog.test.key\""));
        assert!(conf.contains("php_fastcgi \"unix//h/.devid/run/php84.sock\""));
        assert!(conf.matches("bind 127.0.0.1").count() == 3, "default + blog (https, http), all local only");
        assert!(conf.contains("# skipped evil"), "placeholder injection is skipped");
        assert!(!conf.contains("{env.HOME}"));
    }

    #[test]
    fn render_static_and_proxy() {
        let paths = Paths { home: PathBuf::from("/h/.devid") };
        let spa = Site { mode: Mode::Static, spa: true, ..site("app", "/p/app/dist", "8.4") };
        let dev = Site { mode: Mode::Proxy, upstream: 5173, ..site("erd", "/p/erd", "8.4") };
        let raw = Site { mode: Mode::Proxy, upstream: 3000, pass_host: true, ..site("raw", "/p/raw", "8.4") };
        let conf = render(&paths, &Config::default(), &[spa, dev, raw]);
        assert!(conf.contains("root * \"/p/app/dist\"") && conf.contains("try_files {path} {path}.html /index.html"));
        assert!(!conf.contains("php_fastcgi"));
        assert!(conf.contains("header_regexp Origin \"^https?://erd[.]test(:[0-9]+)?$\""));
        assert!(conf.contains("request_header @devid_own_origin Origin http://localhost:5173"));
        assert!(conf.contains("reverse_proxy localhost:5173 {\n\t\theader_up Host localhost:5173"));
        assert!(conf.contains("\treverse_proxy localhost:3000\n"), "pass_host: no rewrites");
        assert_eq!(conf.matches("handle_errors 502").count(), 4, "https and http block of both proxy sites");
        assert!(!conf.contains("devid_refused") && !conf.contains("requests-"), "no on-demand");
    }

    #[test]
    fn render_on_demand() {
        let paths = Paths { home: PathBuf::from("/h/.devid") };
        let dev = Site {
            mode: Mode::Proxy,
            upstream: 4321,
            port: Some(8001),
            on_demand: Some("dev".into()),
            ..site("devid-site", "/p/site", "8.5")
        };
        let raw = Site { pass_host: true, name: "raw".into(), host: "raw.test".into(), ..dev.clone() };
        let other = Site { mode: Mode::Proxy, upstream: 3000, ..site("erd", "/p/erd", "8.5") };
        let conf = render(&paths, &Config::default(), &[dev, raw, other]);
        assert_eq!(
            conf.matches("\toutput file \"/h/.devid/run/requests-devid-site\" {").count(),
            3,
            "https, http and the local port"
        );
        assert_eq!(conf.matches("@devid_refused vars_regexp {http.error.message} \"^dial \"").count(), 6);
        assert_eq!(conf.matches("reverse_proxy \"unix//h/.devid/run/wake.sock\" {").count(), 6);
        assert_eq!(conf.matches("respond \"Nothing answers on localhost:3000").count(), 2, "erd as before");

        let block = &conf[conf.find("https://devid-site.test:8443 {").unwrap()..];
        let block = &block[..block.find("\n}\n").unwrap()];
        for line in [
            "\t\t\t\tmethod GET\n",
            "\t\t\t\theader_up X-Devid-Site devid-site\n",
            "\t\t\t\theader_up X-Devid-Method {method}\n",
            "\t\t\t\t@devid_ready status 418\n",
            // No idle connection is kept open to the dev server: the idle check would see it.
            "\treverse_proxy localhost:4321 {\n\
             \t\theader_up Host localhost:4321\n\
             \t\ttransport http {\n\
             \t\t\tkeepalive off\n\
             \t\t}\n\
             \t}\n",
            // The same request, its Host rewritten as on the main path, goes to the dev server.
            "\t\t\t\thandle_response @devid_ready {\n\
             \t\t\t\t\treverse_proxy localhost:4321 {\n\
             \t\t\t\t\t\theader_up Host localhost:4321\n\
             \t\t\t\t\t\ttransport http {\n\
             \t\t\t\t\t\t\tkeepalive off\n\
             \t\t\t\t\t\t}\n\
             \t\t\t\t\t}\n\
             \t\t\t\t}\n",
            "\t\thandle {\n\t\t\trespond \"Nothing answers on localhost:4321 for devid-site.test.",
            "\t\t\trequest delete\n\t\t\tresp_headers delete\n",
        ] {
            assert!(block.contains(line), "missing {line:?} in {block}");
        }
        let raw = &conf[conf.find("https://raw.test:8443 {").unwrap()..];
        assert!(raw.starts_with(
            "https://raw.test:8443 {\n\tbind 127.0.0.1\n\ttls \"/h/.devid/certs/raw.test.crt\" \"/h/.devid/certs/raw.test.key\"\n\
             \treverse_proxy localhost:4321 {\n\t\ttransport http {\n\t\t\tkeepalive off\n\t\t}\n\t}\n"
        ));
        assert_eq!(conf.matches("keepalive off").count(), 12, "on demand only: 2 sites x 3 blocks x 2 proxies");
    }

    #[test]
    fn render_local_port() {
        let paths = Paths { home: PathBuf::from("/h/.devid") };
        let saas = Site { port: Some(8000), ..site("saas", "/p/saas/public", "8.5") };
        let conf = render(&paths, &Config::default(), &[saas]);
        assert!(conf.contains("trusted_proxies static 127.0.0.1/8 ::1"));
        assert!(
            conf.contains("# saas on its local port\nhttp://:8000 {\n\tbind 127.0.0.1\n\troot * \"/p/saas/public\"")
        );
        assert_eq!(conf.matches("php_fastcgi").count(), 3, "https, http and the local port");
    }
}
