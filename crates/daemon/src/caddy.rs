//! Caddy, an alternative web server (D-005, D-015). Devid owns the certificates, so automatic
//! HTTPS and the admin API are off; a config change restarts Caddy (it has no SIGHUP reload).

use crate::{
    ca,
    config::Config,
    nginx::quotable_without,
    paths::Paths,
    php,
    sites::{Mode, Site},
    supervisor::Spec,
};
use std::{
    fmt::Write as _,
    fs, io,
    path::{Path, PathBuf},
    process::Command,
};

fn err(msg: impl Into<String>) -> io::Error {
    io::Error::other(msg.into())
}

/// Caddyfile placeholders use braces, so paths with `{`/`}` are rejected as well.
fn quote(path: &Path) -> Option<String> {
    quotable_without(path, &['{', '}'])
}

pub fn dir(paths: &Paths) -> PathBuf {
    paths.home.join("caddy")
}

pub fn bin(paths: &Paths) -> PathBuf {
    dir(paths).join("bin/caddy")
}

pub fn conf(paths: &Paths) -> PathBuf {
    dir(paths).join("Caddyfile")
}

pub fn installed(paths: &Paths) -> bool {
    bin(paths).is_file()
}

/// Install a Caddy v2 binary (e.g. the official release).
// shortcut: installs from a local file only; downloading release assets comes with the Phase 5 pipeline.
pub fn install(paths: &Paths, from: &Path) -> io::Result<()> {
    let out = crate::webserver::probe(from, &["version"])?;
    if !String::from_utf8_lossy(&out.stdout).trim_start().starts_with("v2.") {
        return Err(err(format!("{} does not look like Caddy v2", from.display())));
    }
    let target = bin(paths);
    fs::create_dir_all(target.parent().expect("bin has a parent"))?;
    let tmp = target.with_extension("new");
    fs::copy(from, &tmp)?;
    fs::rename(tmp, target)
}

/// One Caddyfile for all sites, on 127.0.0.1 only. Unsafe paths are skipped with a comment.
pub fn render(paths: &Paths, config: &Config, sites: &[Site]) -> String {
    let (http, https) = (config.http_port, config.https_port);
    let q = |p: &Path| quote(p).expect("Devid's own paths are quotable");
    let mut c = format!(
        "# Generated by Devid; changes are overwritten.\n\
         {{\n\
         \tadmin off\n\
         \tauto_https off\n\
         \tstorage file_system {data}\n\
         \tlog {{\n\
         \t\toutput file {log}\n\
         \t\tlevel WARN\n\
         \t}}\n\
         }}\n\
         \n\
         http://:{http} {{\n\
         \tbind 127.0.0.1\n\
         \trespond \"No Devid site for this host.\" 404\n\
         }}\n",
        data = q(&dir(paths).join("data")),
        log = q(&paths.log_dir().join("caddy-error.log")),
    );
    for site in sites {
        let (Some(crt), Some(key), Some(body)) =
            (quote(&ca::site_cert(paths, &site.host)), quote(&ca::site_key(paths, &site.host)), site_body(paths, site))
        else {
            let _ = writeln!(c, "\n# skipped {}: path contains characters Caddy cannot quote safely", site.name);
            continue;
        };
        // Caddy rejects `tls` in a block that also listens on plain HTTP, so each site gets an
        // HTTPS block and an HTTP block with the same body.
        let _ = write!(
            c,
            "\nhttps://{host}:{https} {{\n\
             \tbind 127.0.0.1\n\
             \ttls {crt} {key}\n\
             {body}\
             }}\n\
             \nhttp://{host}:{http} {{\n\
             \tbind 127.0.0.1\n\
             {body}\
             }}\n",
            host = site.host,
        );
    }
    c
}

/// The part of a site's blocks that depends on its mode; None if a path cannot be quoted.
fn site_body(paths: &Paths, site: &Site) -> Option<String> {
    let hidden = "\t@hidden {\n\t\tpath /.*\n\t\tnot path /.well-known/*\n\t}\n\trespond @hidden 403\n";
    Some(match site.mode {
        Mode::Php => {
            let root = quote(&site.docroot)?;
            let sock = quote(Path::new(&format!("unix/{}", php::socket(paths, &site.php).display())))?;
            format!("\troot * {root}\n\tencode\n{hidden}\tphp_fastcgi {sock}\n\tfile_server\n")
        }
        Mode::Static => {
            let root = quote(&site.docroot)?;
            let spa = if site.spa { " /index.html" } else { "" };
            format!("\troot * {root}\n\tencode\n{hidden}\ttry_files {{path}} {{path}}.html{spa}\n\tfile_server\n")
        }
        Mode::Proxy => {
            let (host, up) = (&site.host, site.upstream);
            let down = format!(
                "\thandle_errors 502 {{\n\
                 \t\trespond \"Nothing answers on localhost:{up} for {host}. Start its dev server (or its command in Devid).\" 502\n\
                 \t}}\n"
            );
            if site.pass_host {
                return Some(format!("\treverse_proxy localhost:{up}\n{down}"));
            }
            // As in nginx: Host and the site's own Origin become the dev server's (A1).
            let own = host.replace('.', "[.]");
            format!(
                "\t@devid_own_origin header_regexp Origin \"^https?://{own}(:[0-9]+)?$\"\n\
                 \trequest_header @devid_own_origin Origin http://localhost:{up}\n\
                 \treverse_proxy localhost:{up} {{\n\
                 \t\theader_up Host localhost:{up}\n\
                 \t}}\n\
                 {down}"
            )
        }
    })
}

/// Write the Caddyfile only if `caddy validate` accepts it. Returns whether it changed.
pub fn write_checked(paths: &Paths, text: &str) -> io::Result<bool> {
    let conf = conf(paths);
    if fs::read_to_string(&conf).is_ok_and(|old| old == text) {
        return Ok(false);
    }
    fs::create_dir_all(dir(paths).join("data"))?;
    fs::create_dir_all(paths.log_dir())?;
    let candidate = conf.with_extension("new");
    fs::write(&candidate, text)?;
    let out =
        Command::new(bin(paths)).args(["validate", "--adapter", "caddyfile", "--config"]).arg(&candidate).output()?;
    if !out.status.success() {
        let _ = fs::remove_file(&candidate);
        let detail = String::from_utf8_lossy(&out.stderr);
        let last = detail.lines().rev().find(|l| !l.trim().is_empty()).unwrap_or("").trim();
        return Err(err(format!("caddy rejected the new config: {last}")));
    }
    fs::rename(candidate, conf)?;
    Ok(true)
}

pub fn spec(paths: &Paths) -> Spec {
    Spec {
        program: bin(paths),
        args: vec!["run".into(), "--adapter".into(), "caddyfile".into(), "--config".into(), conf(paths).into()],
        // Caddy reads XDG dirs for autosave; keep them inside Devid's folder.
        env: vec![
            ("XDG_DATA_HOME".into(), dir(paths).join("data").into()),
            ("XDG_CONFIG_HOME".into(), dir(paths).join("config").into()),
        ],
        // Caddy writes no pid file; the supervisor tracks the child directly.
        pid_file: paths.run_dir().join("caddy.pid"),
        comm: "caddy",
        stop_signal: libc::SIGTERM,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn site(name: &str, docroot: &str, php: &str) -> Site {
        Site {
            name: name.into(),
            host: format!("{name}.test"),
            path: PathBuf::from(docroot),
            docroot: PathBuf::from(docroot),
            php: php.into(),
            linked: true,
            preset: "php",
            ..Site::default()
        }
    }

    #[test]
    fn render_sites() {
        let paths = Paths { home: PathBuf::from("/h/.devid") };
        let conf = render(
            &paths,
            &Config::default(),
            &[site("blog", "/p/blog/public", "8.4"), site("evil", "/p/{env.HOME}", "8.5")],
        );
        assert!(conf.contains("admin off") && conf.contains("auto_https off"));
        assert!(conf.contains("https://blog.test:8443 {") && conf.contains("http://blog.test:8088 {"));
        assert!(!conf.contains(", https://"), "Caddy rejects http and https addresses sharing a tls block");
        assert!(conf.contains("tls \"/h/.devid/certs/blog.test.crt\" \"/h/.devid/certs/blog.test.key\""));
        assert!(conf.contains("php_fastcgi \"unix//h/.devid/run/php84.sock\""));
        assert!(conf.matches("bind 127.0.0.1").count() == 3, "default + blog (https, http), all local only");
        assert!(conf.contains("# skipped evil"), "placeholder injection is skipped");
        assert!(!conf.contains("{env.HOME}"));
    }

    #[test]
    fn render_static_and_proxy() {
        let paths = Paths { home: PathBuf::from("/h/.devid") };
        let spa = Site { mode: Mode::Static, spa: true, ..site("app", "/p/app/dist", "8.4") };
        let dev = Site { mode: Mode::Proxy, upstream: 5173, ..site("erd", "/p/erd", "8.4") };
        let raw = Site { mode: Mode::Proxy, upstream: 3000, pass_host: true, ..site("raw", "/p/raw", "8.4") };
        let conf = render(&paths, &Config::default(), &[spa, dev, raw]);
        assert!(conf.contains("root * \"/p/app/dist\"") && conf.contains("try_files {path} {path}.html /index.html"));
        assert!(!conf.contains("php_fastcgi"));
        assert!(conf.contains("header_regexp Origin \"^https?://erd[.]test(:[0-9]+)?$\""));
        assert!(conf.contains("request_header @devid_own_origin Origin http://localhost:5173"));
        assert!(conf.contains("reverse_proxy localhost:5173 {\n\t\theader_up Host localhost:5173"));
        assert!(conf.contains("\treverse_proxy localhost:3000\n"), "pass_host: no rewrites");
        assert_eq!(conf.matches("handle_errors 502").count(), 4, "https and http block of both proxy sites");
    }
}
